class HardwareSimulator:
    """Provides simulated hardware telemetry for demo and testing mode."""

    def __init__(self):
        self.active_scenario_key = "usb_3_0"

    def set_scenario(self, scenario_key: str):
        if scenario_key in SCENARIOS:
            self.active_scenario_key = scenario_key

    def get_laptop_telemetry(self) -> LaptopBatteryInfo:
        sc = SCENARIOS[self.active_scenario_key]
        return LaptopBatteryInfo(
            percent=sc.laptop_pct,
            is_plugged=sc.laptop_plugged,
            power_source="AC Wall Adapter (Simulated)" if sc.laptop_plugged else "Laptop Internal Battery (Simulated)",
            secs_left=int((sc.laptop_pct / 100.0) * 9000),
            discharge_rate_w=sc.laptop_discharge_w if not sc.laptop_plugged else 0.0,
            voltage_v=15.8,
            remaining_mwh=sc.laptop_pct * 550.0,
            full_capacity_mwh=55000.0,
            health_percent=94.5,
            status_text="[DEMO MODE] Discharging (Simulated)" if not sc.laptop_plugged else "[DEMO MODE] AC Power (Simulated)",
            is_available=True
        )

    def get_phone_info(self) -> PhoneConnectionInfo:
        sc = SCENARIOS[self.active_scenario_key]
        return PhoneConnectionInfo(
            is_connected=sc.phone_connected,
            connection_mode=sc.connection_mode,
            device_name=sc.phone_name,
            device_serial="DEMO-SIM-00123",
            manufacturer="Simulated Device",
            battery_percent=sc.phone_pct,
            battery_status="Charging (Simulated)",
            battery_voltage_v=sc.voltage_v,
            charging_current_ma=sc.current_ma,
            charging_power_w=sc.power_w,
            battery_temp_c=sc.temp_c,
            battery_health="Good" if (sc.temp_c or 0) < 40 else "Overheat",
            usb_powered=True,
            ac_powered=False,
            detected_usb_controller=f"Simulated Controller ({sc.port_spec_key})",
            telemetry_source="[DEMO SIMULATOR] Synthetic Test Telemetry",
            telemetry_limitations_reason=None
        )
